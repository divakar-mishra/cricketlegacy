import fs from 'node:fs';
import path from 'node:path';
import {
  avatarGeneratedRoot,
  layerForAsset,
  repoRoot,
  runtimePathForAsset,
  validateAvatarPack,
} from './avatar-pack-lib.mjs';

const { assets, presets } = validateAvatarPack();
fs.mkdirSync(avatarGeneratedRoot, { recursive: true });

const sourceLines = assets.map((asset) => {
  const runtimePath = runtimePathForAsset(asset).split(path.sep).join('/');
  return `  ${JSON.stringify(asset.id)}: require(${JSON.stringify(`../../../assets/avatar/runtime/${runtimePath}`)}),`;
});
const metadata = assets.map((asset) => ({
  id: asset.id,
  category: asset.category,
  layer: layerForAsset(asset),
  ...(asset.sex ? { sex: asset.sex } : {}),
  ...(asset.rig ? { rig: asset.rig } : {}),
  ...(asset.hidesHair ? { hidesHair: true } : {}),
}));

const registrySource = `// Generated by scripts/generate-avatar-registry.mjs. Do not edit by hand.
import type { ImageSourcePropType } from 'react-native';
import type { AvatarAssetMetadata } from '../types';

export const avatarAssetSources: Readonly<Record<string, ImageSourcePropType>> = {
${sourceLines.join('\n')}
};

export const avatarAssetMetadata = ${JSON.stringify(metadata, null, 2)} as const satisfies readonly AvatarAssetMetadata[];

export const AVATAR_ASSET_COUNT = avatarAssetMetadata.length;
`;

const presetsSource = `// Generated from the supplied presets_300.json. Do not edit by hand.
import type { AvatarPreset } from '../types';

export const avatarPresets = ${JSON.stringify(presets, null, 2)} as const satisfies readonly AvatarPreset[];

export const AVATAR_PRESET_COUNT = avatarPresets.length;
`;

fs.writeFileSync(path.join(avatarGeneratedRoot, 'avatarAssets.generated.ts'), registrySource);
fs.writeFileSync(path.join(avatarGeneratedRoot, 'avatarPresets.generated.ts'), presetsSource);
console.log(
  `[avatar-pack] generated ${assets.length} literal Metro assets and ${presets.length} presets in ${path.relative(repoRoot, avatarGeneratedRoot)}`,
);
